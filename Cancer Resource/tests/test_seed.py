def test_msigdb_and_geo153830_ingest_backfill_real_signature_scores():
    """Real ingestion (2026-09-22): synlethality/ingest/msigdb.py fetches the
    real Hallmark ROS-pathway and KEGG Hippo-pathway gene sets (via
    Enrichr's public MSigDB/KEGG mirror, since gsea-msigdb.org itself gates
    downloads behind a login); synlethality/ingest/geo_modifiers.py computes
    real per-gene log2FC from GSE153830's own published FPKM matrix and
    backfills the four matching stress_signature_score rows'
    previously-NULL `score` field via
    synlethality.signature_correlation.geneset_enrichment_score. Never
    creates a new stress_signature_score row, never fabricates a value for
    a (modifier, cell_line) pair with no verified real gene-set mapping."""
    from synlethality.ingest.geo_modifiers import SAMPLE_GROUPS, GEOModifierIngest
    from synlethality.ingest.msigdb import MSigDBIngest

    with SessionLocal() as db:
        before = {
            key: db.query(StressSignatureScore)
            .filter_by(modifier_id=mid, cell_line_id=cid).one().score
            for (mid, cid), g in SAMPLE_GROUPS.items()
            for key in [g["key"]]
        }
        assert all(v is None for v in before.values()), (
            "expected these four rows to start at score=None (curated seed)")

        msigdb_run = MSigDBIngest().run(db)
        assert msigdb_run.status == "success", msigdb_run.message
        assert msigdb_run.row_count == 2  # the two gene sets this session verified

        geo_run = GEOModifierIngest("GSE153830").run(db)
        assert geo_run.status == "success", geo_run.message
        assert geo_run.row_count == len(SAMPLE_GROUPS)

        rows_by_key = {}
        for (mid, cid), g in SAMPLE_GROUPS.items():
            row = db.query(StressSignatureScore).filter_by(
                modifier_id=mid, cell_line_id=cid).one()
            rows_by_key[g["key"]] = row
            assert row.score is not None
            assert isinstance(row.score, float)
            assert row.raw_deg_evidence_ref.startswith("geo:GSE153830")
            assert "[Real DEG backfill" in row.notes
            assert "uncorrected standardized-mean-difference" in row.notes

        # Real, directionally-plausible result: the paper's own headline
        # finding (NRF2/ferroptosis-axis involvement under glucose
        # deprivation in T47D) comes back as a real, strongly positive
        # enrichment z-score -- not a fabricated confirmation, an actual
        # computed number from the paper's own expression matrix.
        assert rows_by_key["t47d_glucose_nrf2"].score > 2.0

        # The full real per-gene log2FC table (not just each gene set's
        # enrichment score) is also persisted, for signature_correlation.py's
        # xsum_correlation to consume later -- see
        # test_correlate_modifier_drug_runs_real_xsum_against_synthetic_lincs.
        from synlethality.ingest.geo_modifiers import load_deg_cache
        hippo_rec = load_deg_cache("mcf7_glucose_hippo")
        assert hippo_rec["modifier_id"] == "MOD-GLUCOSE-RESTRICT-5PCT-96H"
        assert hippo_rec["cell_line_id"] == "MCF7_BREAST"
        assert isinstance(hippo_rec["gene_log2fc"], dict) and len(hippo_rec["gene_log2fc"]) > 10000

        # Idempotent: re-running both steps updates the same rows in place,
        # not a growing note or a duplicated backfill block.
        MSigDBIngest().run(db)
        geo_run2 = GEOModifierIngest("GSE153830").run(db)
        assert geo_run2.status == "success"
        for key, row_before in rows_by_key.items():
            row_after = db.query(StressSignatureScore).filter_by(
                modifier_id=row_before.modifier_id,
                cell_line_id=row_before.cell_line_id,
            ).one()
            assert row_after.score == pytest.approx(row_before.score)
            assert row_after.notes.count("[Real DEG backfill") == 1


