def test_no_fabricated_combined_metrics():
    """Curated seed carries a combined-effect metric only where a paper's own
    number was directly extracted and cited (REAL_COMBINED_EFFECT_METRICS,
    2026-09-23) -- every other row stays qualitative-only (documented spec
    deviation), never an estimated or computed placeholder."""
    for it in _all(InteractionEffect):
        key = (it.modifier_id, it.drug_id, it.cell_line_id)
        if key in REAL_COMBINED_EFFECT_METRICS:
            assert it.combined_effect_metric == pytest.approx(REAL_COMBINED_EFFECT_METRICS[key])
        else:
            assert it.combined_effect_metric is None, (
                f"{key} has an unexpected combined_effect_metric -- add it to "
                "REAL_COMBINED_EFFECT_METRICS with its source, or this may be "
                "a fabricated/estimated value.")
    assert len(REAL_COMBINED_EFFECT_METRICS) == len([
        it for it in _all(InteractionEffect) if it.combined_effect_metric is not None
    ])


