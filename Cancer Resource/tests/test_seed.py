"""Seed-data integrity tests.

These guard the evidence-integrity rules from the build spec:
no fabricated quantitative metrics, citations on every claim, and
protocol parameters preserved on every modifier.

The isolated test database is created and seeded when synlethality.main is
imported (see conftest.py for the temp DATABASE_URL).
"""

