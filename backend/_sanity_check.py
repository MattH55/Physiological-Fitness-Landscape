# 4. Check for biomarkers where mean - 3.8*sd < 0 (would show negative x-axis)
print("\n" + "=" * 60)
print("4. BIOMARKERS WHERE mean - 3.8*sd < 0 (negative x-axis range)")
print("=" * 60)
c.execute("""
    SELECT bd.name, bd.units, pd.mean, pd.sd,
           (pd.mean - 3.8 * pd.sd) as x_lo,
           (pd.mean + 3.8 * pd.sd) as x_hi,
           bd.valid_domain_min, bd.valid_domain_max
    FROM population_distribution pd
    JOIN biomarker bd ON pd.biomarker_id = bd.id
    WHERE pd.sex = 'all' AND pd.age_band = 'all'
      AND pd.mean - 3.8 * pd.sd < 0
""")
rows = c.fetchall()
if rows:
    for r in rows:
        clamped_lo = max(r['x_lo'], r['valid_domain_min'] if r['valid_domain_min'] is not None else 0)
        print(f"  {r['name']} ({r['units']}): mean={r['mean']}, sd={r['sd']}")
        print(f"    raw x_lo={r['x_lo']:.2f}, clamped x_lo={clamped_lo:.2f}, domain=[{r['valid_domain_min']}, {r['valid_domain_max']}]")
else:
    print("  OK - No biomarkers with negative x-axis range")

