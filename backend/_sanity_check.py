# 1. Negative distribution values
print("=" * 60)
print("1. NEGATIVE DISTRIBUTION VALUES")
print("=" * 60)
c.execute("""
    SELECT bd.name, bd.units, pd.sex, pd.age_band,
           pd.mean, pd.sd, pd.p10, pd.p25, pd.p50, pd.p75, pd.p90
    FROM population_distribution pd
    JOIN biomarker bd ON pd.biomarker_id = bd.id
    WHERE pd.mean < 0 OR pd.p10 < 0 OR pd.p25 < 0
       OR pd.p50 < 0 OR pd.p75 < 0 OR pd.p90 < 0
""")
